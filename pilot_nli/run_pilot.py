def auroc(labels, scores):
    pos = [s for s, y in zip(scores, labels) if y]
    neg = [s for s, y in zip(scores, labels) if not y]
    return sum((p > n) + 0.5 * (p == n) for p in pos for n in neg) / (len(pos) * len(neg))


def main() -> int:
    frozen = (HERE / "PREREG.sha16").read_text().strip()
    assert hashlib.sha256((HERE / "PREREG.md").read_bytes()).hexdigest()[:16] == frozen, (
        "PREREG changed after freezing"
    )
    sys.path.insert(0, SEMIF)
    from modeling_openjev import OpenJevCrossEncoder

    t0 = time.time()
    jev = OpenJevCrossEncoder(SEMIF, subfolder="qwen3.5-0.8b-nli-v2s-long")
    print(f"loaded in {time.time() - t0:.1f}s", flush=True)

    def p(prem, hyp):
        return float(jev.predict([(prem, hyp)])[0][1])  # [contradiction, entailment, neutral]

    ok, bad = (
        p("France's capital city is Paris.", "Paris is the capital of France."),
        p("France's capital city is Paris.", "Berlin is the capital of France."),
    )
    print(f"sanity control: supported {ok:.3f} vs unsupported {bad:.3f}")
    out = {"prereg_sha16": frozen, "control": {"supported": ok, "unsupported": bad}}
    if not ok > bad:
        out["verdict"] = "INSTRUMENT FAILED sanity control — no result"
        (HERE / "results.json").write_text(json.dumps(out, indent=1))
        print(out["verdict"])
        return 1
    prem = premises()
    items, labels, scores, lens = [], [], [], []
    for pid, good, badh in PAIRS:
        sg, sb = p(prem[pid], good), p(prem[pid], badh)
        items.append(
            {
                "premise": pid,
                "supported": good,
                "p_supported": sg,
                "unsupported": badh,
                "p_unsupported": sb,
            }
        )
        labels += [1, 0]
        scores += [sg, sb]
        lens += [len(good), len(badh)]
        print(
            f"{pid}: supported {sg:.3f} | unsupported {sb:.3f} {'OK' if sg > sb else 'MISS'}",
            flush=True,
        )
    pair_acc = sum(i["p_supported"] > i["p_unsupported"] for i in items)
    a, a_len = auroc(labels, scores), auroc(labels, lens)
    adopt = pair_acc >= 9 and a >= a_len + 0.10
    out.update(
        items=items,
        pairwise=f"{pair_acc}/10",
        auroc=a,
        auroc_length_control=a_len,
        verdict="ADOPT as drafting aid" if adopt else "DROP",
        premises=prem,
    )
    (HERE / "results.json").write_text(json.dumps(out, indent=1))
    print(
        f"pairwise {pair_acc}/10 | AUROC {a:.3f} vs length control {a_len:.3f} -> {out['verdict']}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
